create table if not exists public.lr_documents (
  id text primary key,
  name text not null,
  size_bytes bigint not null default 0,
  chunk_count integer not null default 0,
  status text not null default 'ready',
  uploaded_at timestamptz not null default now(),
  storage_path text,
  public_url text,
  error_message text,
  visibility_scope text not null default 'unclassified',
  publication_status text not null default 'draft',
  source_id text,
  source_type text,
  owner_type text,
  owner_id text,
  approved_by text,
  approved_at timestamptz,
  published_at timestamptz,
  expires_at timestamptz,
  last_verified_at timestamptz,
  document_version integer not null default 1,
  current_revision integer not null default 1,
  constraint lr_documents_visibility_scope_check
    check (visibility_scope in ('unclassified', 'private', 'public')),
  constraint lr_documents_publication_status_check
    check (publication_status in ('draft', 'review', 'approved', 'published', 'suspended', 'expired', 'archived')),
  constraint lr_documents_document_version_check
    check (document_version > 0),
  constraint lr_documents_current_revision_check
    check (current_revision > 0),
  constraint lr_documents_telegram_owner_check
    check (owner_type is distinct from 'telegram_chat' or nullif(trim(owner_id), '') is not null),
  constraint lr_documents_approval_metadata_check
    check (
      publication_status not in ('approved', 'published')
      or (
        nullif(trim(approved_by), '') is not null
        and approved_at is not null
        and nullif(trim(source_id), '') is not null
        and nullif(trim(source_type), '') is not null
        and last_verified_at is not null
      )
    ),
  constraint lr_documents_published_scope_check
    check (
      publication_status <> 'published'
      or (visibility_scope = 'public' and published_at is not null)
    )
);

create index if not exists lr_documents_uploaded_at_idx
  on public.lr_documents (uploaded_at desc);

