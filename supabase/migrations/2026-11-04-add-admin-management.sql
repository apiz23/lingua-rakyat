





create table if not exists public.lr_admin_roles (
  id bigint generated by default as identity primary key,
  email text not null,
  role text not null,
  granted_by text not null,
  granted_at timestamptz not null default now(),
  revoked_at timestamptz,
  revoked_by text,
  reason text,
  constraint lr_admin_roles_role_check
    check (role in ('super_admin', 'document_manager', 'reviewer', 'publisher', 'auditor')),
  constraint lr_admin_roles_actor_check check (nullif(trim(email), '') is not null),
  constraint admin_roles_grantor_check check (nullif(trim(granted_by), '') is not null)
);

create unique index if not exists lr_admin_roles_active_unique
  on public.lr_admin_roles (email, role)
  where revoked_at is null;

create index if not exists lr_admin_roles_email_idx
  on public.lr_admin_roles (email, revoked_at);

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_id text not null,
  actor_role text,
  action text not null,
  target_type text not null,
  target_id text,
  reason text,
  state_from text,
  state_to text,
  correlation_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint admin_audit_actor_check check (nullif(trim(actor_id), '') is not null),
  constraint admin_audit_action_check check (nullif(trim(action), '') is not null)
);

create index if not exists admin_audit_log_created_at_idx
  on public.admin_audit_log (created_at desc);

create index if not exists admin_audit_log_target_idx
  on public.admin_audit_log (target_type, target_id, created_at desc);

alter table public.lr_admin_roles enable row level security;
alter table public.admin_audit_log enable row level security;
revoke all on table public.lr_admin_roles from anon, authenticated;
revoke all on table public.admin_audit_log from anon, authenticated;
revoke update, delete on table public.admin_audit_log from anon, authenticated;
