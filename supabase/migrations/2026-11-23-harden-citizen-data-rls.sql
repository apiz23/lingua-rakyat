-- Harden citizen-data tables against direct PostgREST access.
--
-- The backend is the only client for these tables and now reaches them with the
-- service role after verifying identity/ownership. The anon and authenticated
-- Postgres roles must therefore never read or write them directly, otherwise a
-- leaked publishable key would expose every citizen's chat history or allow
-- forged feedback/share rows.
--
-- Review before applying; this migration is not run by the application.

-- ---------------------------------------------------------------------------
-- Tables referenced by the backend but not defined by an earlier migration.
-- ---------------------------------------------------------------------------

create table if not exists public.lr_shared_answers (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,
  question text not null,
  answer text not null,
  sources jsonb not null default '[]'::jsonb,
  language text not null default 'ms',
  confidence double precision not null default 0,
  confidence_label text not null default '',
  agency text not null default '',
  user_id text,
  created_at timestamptz not null default now()
);

alter table public.lr_shared_answers
  add column if not exists confidence double precision not null default 0,
  add column if not exists confidence_label text not null default '',
  add column if not exists agency text not null default '',
  add column if not exists user_id text;

create index if not exists idx_lr_shared_answers_user_id
  on public.lr_shared_answers (user_id);

create table if not exists public.lr_feedback (
  id bigint generated by default as identity primary key,
  session_id text not null,
  question text not null,
  doc_id text not null default '',
  feedback text not null check (feedback in ('up', 'down')),
  created_at timestamptz not null default now()
);

create index if not exists lr_feedback_created_at_idx
  on public.lr_feedback (created_at desc);

-- ---------------------------------------------------------------------------
-- Default-deny for browser roles. The service role bypasses RLS and is the
-- only path the backend uses.
-- ---------------------------------------------------------------------------

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'lr_chat_messages',
    'lr_shared_answers',
    'lr_feedback',
    'lr_eval_records',
    'lr_tg_sessions',
    'lr_wa_sessions'
  ]
  loop
    if to_regclass('public.' || table_name) is not null then
      execute format('alter table public.%I enable row level security', table_name);
      execute format('revoke all on table public.%I from anon, authenticated', table_name);
    end if;
  end loop;
end $$;

notify pgrst, 'reload schema';
